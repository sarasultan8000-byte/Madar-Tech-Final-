function localizedValue(item, key) {
    if (!item || typeof item !== "object") return undefined;
    if (locale === "en") {
        const englishValue = item[key + "En"];
        return typeof englishValue === "string"
            && englishValue.trim()
            && !/[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/.test(englishValue)
            ? englishValue
            : undefined;
    }
    return typeof item[key] === "string" ? item[key] : undefined;
}

function pickPublicFields(item, fields) {
    const result = {};
    fields.forEach((field) => {
        const value = item[field];
        if (typeof value === "string" || typeof value === "number" || typeof value === "boolean") {
            result[field] = value;
        }
    });
    return result;
}

function isLocalContentVisible(item) {
    const status = typeof item.status === "string" ? item.status.toLowerCase() : "";
    return item.visible !== false && !["hidden", "draft", "inactive", "unpublished"].includes(status);
}

function projectLocalDraft(draft) {
    const sectionFields = [
        "id", "sectionKey", "name", "nameEn", "title", "titleEn", "subtitle", "subtitleEn",
        "description", "descriptionEn", "image", "order"
    ];
    const sectionList = Array.isArray(draft.sections)
        ? draft.sections.filter((section) => section && typeof section === "object").map((section) => {
            if (!isLocalContentVisible(section)) {
                return { ...pickPublicFields(section, ["id", "sectionKey", "order"]), visible: false };
            }
            return { ...pickPublicFields(section, sectionFields), visible: true };
        })
        : null;
    const collection = (key, fields) => Array.isArray(draft[key])
        ? draft[key]
            .filter((item) => item && typeof item === "object" && isLocalContentVisible(item))
            .map((item) => pickPublicFields(item, fields))
        : null;
    const settings = draft.settings && typeof draft.settings === "object"
        ? pickPublicFields(draft.settings, [
            "siteName", "siteNameEn", "siteDescription", "siteDescriptionEn",
            "contactEmail", "contactPhone", "location", "locationEn"
        ])
        : null;

    return {
        sections: sectionList,
        services: collection("services", [
            "id", "title", "titleEn", "description", "descriptionEn", "icon", "image", "order"
        ]),
        projects: collection("projects", [
            "id", "title", "titleEn", "category", "categoryEn", "shortDescription", "shortDescriptionEn",
            "description", "descriptionEn", "image", "url", "order"
        ]),
        teamMembers: collection("teamMembers", [
            "id", "name", "nameEn", "role", "roleEn", "bio", "bioEn", "image", "order"
        ]),
        testimonials: collection("testimonials", [
            "id", "name", "nameEn", "text", "textEn", "image", "rating", "order"
        ]),
        faq: collection("faq", [
            "id", "question", "questionEn", "answer", "answerEn", "order"
        ]),
        settings
    };
}

