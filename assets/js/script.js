function ensureManagedSectionSlots() {
    if (managedSectionSlots.size) return;
    managedSectionIds.forEach((id) => {
        const element = document.getElementById(id);
        if (!element || !element.parentNode) return;
        const slot = document.createComment("managed-section-slot");
        element.parentNode.insertBefore(slot, element);
        managedSectionElements.set(id, element);
        managedSectionSlots.set(id, slot);
    });
}

function createCustomSection(section) {
    const sectionElement = createElement("section", "section section-light cms-public-section");
    sectionElement.id = "cms-section-" + String(section.id || section.sectionKey || "custom").replace(/[^a-zA-Z0-9_-]/g, "-");
    sectionElement.dataset.contentKey = section.sectionKey || "";
    sectionElement.hidden = !isPubliclyVisible(section);
    const container = createElement("div", "container");
    const heading = createElement("div", "section-heading");
    const subtitle = localizedValue(section, "subtitle");
    const title = localizedValue(section, "title") || localizedValue(section, "name");
    const description = localizedValue(section, "description");
    if (subtitle) heading.append(createElement("span", "eyebrow", subtitle));
    if (title) heading.append(createElement("h2", "", title));
    if (description) heading.append(createElement("p", "", description));
    container.append(heading);

    const key = section.sectionKey;
    if (key === "faq" && Array.isArray(publishedContent.faq)) {
        const list = createElement("div", "faq-list");
        renderFaqItems(list, publishedContent.faq);
        if (list.childElementCount) container.append(list);
    } else {
        const items = Array.isArray(publishedContent[key]) ? publishedContent[key] : [];
        const grid = createElement("div", "cms-public-grid");
        items.forEach((item) => {
            const card = createPublicCard(item, key);
            if (card) grid.append(card);
        });
        if (grid.childElementCount) container.append(grid);
    }

    if (locale === "en" && !heading.childElementCount && !container.querySelector(".cms-public-grid, .faq-list") && !section.image) {
        sectionElement.hidden = true;
    }
    sectionElement.append(container);
    return sectionElement;
}

function renderCustomSections() {
    const host = document.getElementById("cmsSections");
    if (!host || !Array.isArray(publishedContent.sections)) return;
    ensureManagedSectionSlots();

    const fixedSectionFor = new Map();
    const entries = [];
    const customSections = [];
    const usedFixedIds = new Set();
    sortByOrder(publishedContent.sections).forEach((section) => {
        let fixedId = managedSectionIds.includes(section.id) && !usedFixedIds.has(section.id) ? section.id : null;
        if (!fixedId && managedSectionIds.includes(section.sectionKey) && !usedFixedIds.has(section.sectionKey)) {
            fixedId = section.sectionKey;
        }
        if (fixedId && managedSectionElements.has(fixedId)) {
            usedFixedIds.add(fixedId);
            fixedSectionFor.set(fixedId, section);
            entries.push({ order: section.order, element: managedSectionElements.get(fixedId) });
        } else {
            customSections.push(section);
            entries.push({ order: section.order, element: createCustomSection(section) });
        }
    });

    managedSectionElements.forEach((element, id) => {
        element.remove();
        if (!fixedSectionFor.has(id)) {
            element.hidden = true;
            entries.push({ order: Number.POSITIVE_INFINITY, element });
        }
    });
    document.querySelectorAll(".cms-public-section").forEach((element) => element.remove());
    customSectionSlots.forEach((slot) => slot.remove());
    customSectionSlots = customSections.map(() => {
        const slot = document.createComment("custom-section-slot");
        host.append(slot);
        return slot;
    });

    const slots = [...managedSectionSlots.values(), ...customSectionSlots];
    slots.sort((first, second) => first === second
        ? 0
        : first.compareDocumentPosition(second) & Node.DOCUMENT_POSITION_FOLLOWING ? -1 : 1);
    entries.sort((first, second) => first.order - second.order);
    entries.forEach((entry, index) => {
        const slot = slots[index];
        slot.parentNode.insertBefore(entry.element, slot);
        if (entry.element.classList.contains("cms-public-section")) observeRevealElements(entry.element);
    });
}

function applyPublishedContent() {
    if (!publishedContent) return;
    const sections = Array.isArray(publishedContent.sections) ? publishedContent.sections : null;
    const sectionIds = ["about", "services", "contact", "faq"];
    if (sections) {
        sectionIds.forEach((id) => {
            const section = sections.find((item) => item.id === id) || sections.find((item) => item.sectionKey === id);
            const target = document.getElementById(id);
            if (!target) return;
            target.hidden = !section || !isPubliclyVisible(section);
            if (!section || target.hidden) return;

            const heading = id === "about" || id === "services"
                ? target.querySelector(".section-heading")
                : target.querySelector(".contact-copy, .faq-heading");
            const eyebrow = heading && heading.querySelector(".eyebrow");
            const title = heading && heading.querySelector("h2");
            const description = heading && heading.querySelector("p");
            const subtitleText = localizedValue(section, "subtitle");
            const titleText = localizedValue(section, "title") || localizedValue(section, "name");
            const descriptionText = localizedValue(section, "description");
            if (eyebrow && subtitleText !== undefined) eyebrow.textContent = subtitleText;
            if (title && titleText !== undefined) title.textContent = titleText;
            if (description && descriptionText !== undefined) description.textContent = descriptionText;

            if (id === "about" && section.image) {
                const imageUrl = safeUrl(section.image);
                const image = target.querySelector(".section-image");
                if (image && imageUrl) {
                    image.src = imageUrl;
                    image.alt = titleText || "";
                }
            }
        });
    }

    if (Array.isArray(publishedContent.services)) renderServices(publishedContent.services);
    if (Array.isArray(publishedContent.faq)) {
        const faqList = document.querySelector("#faq .faq-list");
        if (faqList) renderFaqItems(faqList, publishedContent.faq);
    }

    const settings = publishedContent.settings;
    if (settings) {
        const email = typeof settings.contactEmail === "string" ? settings.contactEmail.trim() : "";
        if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
            publicContactEmail = email;
            document.querySelectorAll("[data-public-email]").forEach((link) => {
                link.href = "mailto:" + email;
                const textNode = Array.from(link.childNodes).find((node) => node.nodeType === Node.TEXT_NODE);
                if (textNode) textNode.textContent = email;
                else link.append(document.createTextNode(email));
            });
        }
        const location = localizedValue(settings, "location");
        if (location !== undefined) {
            document.querySelectorAll('[data-i18n="contact.location"]').forEach((element) => {
                element.textContent = location;
            });
        }
        const siteDescription = localizedValue(settings, "siteDescription");
        if (siteDescription !== undefined) {
            const tagline = document.querySelector(".footer-brand > p");
            if (tagline) tagline.textContent = siteDescription;
            metaDescription.content = siteDescription;
        }
    }
    renderCustomSections();
}

async function loadPublishedContent() {
    if (siteRefreshInProgress) return;
    siteRefreshInProgress = true;
    try {
        const response = await fetch(siteContentEndpoint, {
            headers: { "Accept": "application/json" },
            cache: "no-store",
            credentials: "same-origin"
        });
        if (!response.ok) throw new Error(`Homepage content request failed (HTTP ${response.status}).`);
        const result = await response.json();
        if (result.updatedAt === publishedUpdatedAt) return;
        if (result.draft !== null && (!result.draft || typeof result.draft !== "object" || Array.isArray(result.draft))) {
            throw new Error("The site API returned an invalid draft.");
        }
        publishedUpdatedAt = result.updatedAt;
        publishedContent = result.draft ? projectLocalDraft(result.draft) : null;
        applyPublishedContent();
    } catch (error) {
        console.error("Could not load shared homepage content from the site API.", error);
    } finally {
        siteRefreshInProgress = false;
    }
}

window.setInterval(() => {
    if (!document.hidden) loadPublishedContent();
}, 3000);

function applyLocale() {
    const copy = translations[locale];
    root.lang = locale;
    root.dir = locale === "ar" ? "rtl" : "ltr";
    document.title = locale === "ar" ? "مدار تك | Madar Tech" : "Madar Tech | Learning and development";
    metaDescription.content = copy["page.description"];

    document.querySelectorAll("[data-i18n]").forEach(function (element) {
        const key = element.dataset.i18n;
        const value = copy[key];

        if (value === undefined) {
            return;
        }

        const attribute = element.dataset.i18nAttr;
        if (attribute) {
            element.setAttribute(attribute, value);
        } else {
            element.innerHTML = value;
        }
    });

    languageToggle.textContent = locale === "ar" ? "EN" : "AR";
    languageToggle.setAttribute("aria-label", copy["nav.switchLanguage"]);
    menuBtn.setAttribute("aria-label", copy[menuBtn.getAttribute("aria-expanded") === "true" ? "nav.menuClose" : "nav.menuOpen"]);
    document.querySelector(".scroll-cue").setAttribute("aria-label", copy["hero.scroll"]);
    document.querySelectorAll(".logo, .footer-logo").forEach(function (link) {
        link.setAttribute("aria-label", locale === "ar" ? "مدار تك" : "Madar Tech");
    });
    document.querySelectorAll(".nav-links a").forEach(function (link) {
        link.setAttribute("lang", locale);
    });
    applyPublishedContent();
}

function applyTheme() {
    document.body.classList.toggle("theme-dark", isDark);
    themeToggle.innerHTML = '<svg class="icon theme-icon" aria-hidden="true"><use href="#icon-' + (isDark ? "sun" : "moon") + '"></use></svg>';
    themeToggle.setAttribute("aria-label", translations[locale][isDark ? "nav.lightMode" : "nav.darkMode"]);
    document.querySelector('meta[name="theme-color"]').content = isDark ? "#091a2b" : "#0b2540";
}

function closeMenu() {
    navLinks.classList.remove("show");
    menuBtn.setAttribute("aria-expanded", "false");
    menuBtn.setAttribute("aria-label", translations[locale]["nav.menuOpen"]);
}

languageToggle.addEventListener("click", function () {
    locale = locale === "ar" ? "en" : "ar";
    localStorage.setItem("madar-locale", locale);
    applyLocale();
    applyTheme();
});

themeToggle.addEventListener("click", function () {
    isDark = !isDark;
    localStorage.setItem("madar-theme", isDark ? "dark" : "light");
    applyTheme();
});

menuBtn.addEventListener("click", function () {
    const isExpanded = menuBtn.getAttribute("aria-expanded") === "true";
    menuBtn.setAttribute("aria-expanded", String(!isExpanded));
    navLinks.classList.toggle("show", !isExpanded);
    menuBtn.setAttribute("aria-label", translations[locale][isExpanded ? "nav.menuOpen" : "nav.menuClose"]);
});

navLinks.querySelectorAll("a").forEach(function (link) {
    link.addEventListener("click", closeMenu);
});

window.addEventListener("resize", function () {
    if (window.innerWidth > 991 && menuBtn.getAttribute("aria-expanded") === "true") {
        closeMenu();
    }
});

